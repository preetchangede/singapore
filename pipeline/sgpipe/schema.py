def write_ts(path):
    out = {
        "BUILDING_CLASSES": BUILDING_CLASSES,
        "TREE_KINDS": TREE_KINDS,
        "ROAD_CLASSES": ROAD_CLASSES,
        "RAIL_CLASSES": RAIL_CLASSES,
        "GROUND": [{"name": g[0], "color": g[1], "rough": g[2], "order": g[3]} for g in GROUND],
        "POI_TYPES": POI_TYPES,
    }
    with open(path, "w") as f:
        f.write("// Generated by pipeline/sgpipe/schema.py — do not edit by hand.\n")
        for k, v in out.items():
            f.write(f"export const {k} = {json.dumps(v)} as const;\n")


